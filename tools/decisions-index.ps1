# Kept pure ASCII on purpose: Windows PowerShell 5.1 reads a BOM-less script as ANSI, so a literal
# em dash in a regex or string here would silently become mojibake.
#
# Regenerates decisions-index.md: one row per D-nnn entry in decisions.md, with its title and the
# line it starts on.
#
#     powershell -NoProfile -File tools/decisions-index.ps1          # rewrite decisions-index.md
#     powershell -NoProfile -File tools/decisions-index.ps1 -Check   # exit 1 if it is stale
#
# decisions.md is about 280k tokens. No agent can read it whole, so before this index existed agents
# either skipped it or guessed which entry mattered. Grep the index, then read the one entry with
# Read's offset at the line number given. decisions.md is append-only, so a line number never moves.
#
# An entry whose heading carries no title (D-203, D-204) takes its first non-empty line instead, so
# no row is ever blank.
[CmdletBinding()]
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$source = Join-Path $root 'decisions.md'
$target = Join-Path $root 'decisions-index.md'

$lines = [System.IO.File]::ReadAllLines($source, [System.Text.Encoding]::UTF8)
$rows = New-Object System.Collections.Generic.List[string]

for ($i = 0; $i -lt $lines.Length; $i++) {
    $m = [regex]::Match($lines[$i], '^#{2,4}\s*(D-\d{3})\s*[\u00B7\u2014:-]?\s*(.*)$')
    if (-not $m.Success) { continue }

    $title = $m.Groups[2].Value.Trim()
    if ($title -eq '') {
        for ($j = $i + 1; $j -lt $lines.Length -and $j -lt $i + 8; $j++) {
            if ($lines[$j].Trim() -ne '') { $title = $lines[$j].Trim(); break }
        }
    }
    # A pipe would split the table cell; markdown emphasis is noise in a one-line summary.
    $title = ($title -replace '\|', '/' -replace '\*\*', '').Trim()
    if ($title.Length -gt 160) { $title = $title.Substring(0, 157) + '...' }

    $rows.Add("| $($m.Groups[1].Value) | $($i + 1) | $title |")
}

$body = @(
    '# decisions.md - index'
    ''
    '**Generated by `tools/decisions-index.ps1` from `decisions.md`. Do not edit by hand.**'
    ''
    'Find the decision here, then read only that entry: `Read decisions.md` with `offset` set to the'
    'line below. `decisions.md` is append-only, so the line numbers do not move.'
    ''
    '| Id | Line | Title |'
    '|---|---|---|'
) + $rows

$updated = ($body -join "`n") + "`n"
$current = if (Test-Path $target) { [System.IO.File]::ReadAllText($target, [System.Text.Encoding]::UTF8).Replace("`r`n", "`n") } else { '' }

if ($Check) {
    if ($current -ne $updated) { Write-Output 'decisions-index.md is stale. Run tools/decisions-index.ps1.'; exit 1 }
    Write-Output 'decisions-index.md is current.'
    exit 0
}

[System.IO.File]::WriteAllText($target, $updated, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "decisions-index.md written - $($rows.Count) entries"
